import asyncio
import os
import signal
import threading
import traceback
import weakref
from collections.abc import Callable
from concurrent.futures import ProcessPoolExecutor
from concurrent.futures.process import BrokenProcessPool
from functools import partial

from areal.utils import logging
from areal.utils.constants import (
    PROCESS_KILL_GRACEFUL_TIMEOUT_SECONDS,
    REWARD_CONSECUTIVE_TIMEOUT_THRESHOLD,
    REWARD_TIMEOUT_SECONDS,
)
from areal.utils.proc import kill_process_tree

logger = logging.getLogger("Reward API")


def _get_worker_pids(executor: ProcessPoolExecutor) -> list[int]:
    """Extract worker process IDs from ProcessPoolExecutor."""
    pids = []
    if hasattr(executor, '_processes'):
        # Internal CPython implementation: executor has _processes dict
        pids = list(executor._processes.keys())
    return pids


def _get_device_count_safely() -> int:
    """
    Safely get device count without initializing CUDA context.
    """
    gpu_types = ["nvidia", "davinci"]
    try:
        if os.path.exists("/dev"):
            for gpu_type in gpu_types:
                devices = [
                    f
                    for f in os.listdir("/dev")
                    if f.startswith(gpu_type) and f[len(gpu_type) :].isdigit()
                ]
                if devices:
                    return len(devices)
    except (OSError, ValueError) as e:
        # /dev doesn't exist or can't read (e.g., Windows, macOS)
        logger.debug(f"Could not read device list from /dev, using fallback: {e}")

    # Fallback: assume 8 devices for cautious max_workers calculation
    return 8


